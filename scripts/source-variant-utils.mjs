const VARIANTS = new Map();
for (const group of SAFE_VARIANT_GROUPS) {
  const chars = [...group];
  const canonical = chars[0];
  for (const char of chars) VARIANTS.set(char, canonical);
}

function normalizeWhitespace(text) {
  return String(text || '').replace(/\s+/gu, '').trim();
}

function normalizePunctuation(text) {
  return String(text || '')
    .replace(/[﹑、]/gu, '，')
    .replace(/[﹔;]/gu, '；')
    .replace(/[﹕:]/gu, '：')
    .replace(/[﹗!]/gu, '！')
    .replace(/[﹖?]/gu, '？')
    .replace(/[“”]/gu, '「')
    .replace(/[‘’]/gu, '」')
    .replace(/[〈《]/gu, '《')
    .replace(/[〉》]/gu, '》')
    .replace(/[（]/gu, '(')
    .replace(/[）]/gu, ')');
}

function variantText(text) {
  let out = '';
  for (const char of String(text || '')) out += VARIANTS.get(char) || char;
  return out;
}

function exactVariantKey(text) {
  return variantText(normalizePunctuation(normalizeWhitespace(text)).normalize('NFKC'));
}

function noPunctuationKey(text) {
  return exactVariantKey(text).replace(/[^\p{Script=Han}0-9]/gu, '');
}

