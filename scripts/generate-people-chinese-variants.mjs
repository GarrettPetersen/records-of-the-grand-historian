import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const RAW_SHA256 = '3f23cd71872633f3350875d25bd388e83b60fa71807634c9a600ec26f38a68ab';
const RELATIONS = new Set([
  'kSimplifiedVariant', 'kTraditionalVariant', 'kSemanticVariant',
  'kSpecializedSemanticVariant', 'kZVariant',
]);

// Unihan relations are possible character equivalences, never person identities.
// Undirected/transitive closure deliberately retains ambiguous comparisons.
export function generateChineseVariantModule(raw) {
  if (createHash('sha256').update(raw).digest('hex') !== RAW_SHA256) {
    throw new Error('Expected the pinned Unicode 17.0.0 Unihan_Variants.txt');
  }
  const parents = new Map();
  const root = (character) => {
    if (!parents.has(character)) parents.set(character, character);
    const parent = parents.get(character);
    if (parent !== character) parents.set(character, root(parent));
    return parents.get(character);
  };
  const character = (token) => {
    if (!/^U\+[0-9A-F]{4,6}$/.test(token)) throw new Error(`Invalid Unihan scalar: ${token}`);
    const value = String.fromCodePoint(Number.parseInt(token.slice(2), 16)).normalize('NFKC');
    if ([...value].length !== 1) throw new Error(`Unexpected non-character NFKC value: ${token}`);
    return value;
  };
  for (const line of raw.toString('utf8').split(/\r?\n/)) {
    if (!line || line.startsWith('#')) continue;
    const fields = line.split('\t');
    if (fields.length !== 3) throw new Error(`Malformed Unihan line: ${line}`);
    const [source, relation, targets] = fields;
    if (!RELATIONS.has(relation)) continue;
    const left = character(source);
    for (const annotated of targets.split(' ')) {
      const right = character(annotated.split('<')[0]);
      const a = root(left), b = root(right);
      if (a !== b) {
        const [first, second] = [a, b].sort((x, y) => x.codePointAt(0) - y.codePointAt(0));
        parents.set(second, first);
      }
    }
  }
  const components = new Map();
  for (const value of parents.keys()) {
    const representative = root(value);
    if (!components.has(representative)) components.set(representative, []);
    components.get(representative).push(value);
  }
  const groups = [...components.values()].filter((group) => group.length > 1)
    .map((group) => group.sort((a, b) => a.codePointAt(0) - b.codePointAt(0)).join(''))
    .sort((a, b) => a.codePointAt(0) - b.codePointAt(0));
  return '// Generated by scripts/generate-people-chinese-variants.mjs; do not edit.\n'
    + '// Unicode 17.0.0; Unicode License V3: ../data/unihan/17.0.0/LICENSE.txt\n'
    + '// Possible-equivalence classes ONLY for conservative English-name pruning.\n'
    + `// Raw SHA-256: ${RAW_SHA256}\n`
    + `export const CHINESE_VARIANT_GROUPS = Object.freeze(${JSON.stringify(groups, null, 2)});\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const args = process.argv.slice(2);
  if (args.some((arg) => arg !== '--check')) throw new Error('Usage: node scripts/generate-people-chinese-variants.mjs [--check]');
  const output = path.join(root, 'scripts/lib/people-chinese-variant-data.mjs');
  const generated = generateChineseVariantModule(fs.readFileSync(path.join(root, 'scripts/data/unihan/17.0.0/Unihan_Variants.txt')));
  if (args.includes('--check')) {
    if (fs.readFileSync(output, 'utf8') !== generated) throw new Error('Generated Chinese variant data is stale');
  } else {
    fs.writeFileSync(output, generated);
  }
}
