import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { buildInputFingerprint, contentUnits } from './scripts/lib/people-content.mjs';
import { localCursorRecoveryTargets, reconcileLocalCursorReservationsInLedger, reservePeopleTargetsInLedger, cursorClaimAvailableToWorker } from './scripts/lib/people-work-queue.mjs';

const root = path.dirname(new URL(import.meta.url).pathname);
const write = (name, value) => { const p = path.join(root, name); fs.mkdirSync(path.dirname(p), {recursive:true}); fs.writeFileSync(p, JSON.stringify(value)); };
const target = {book:'fixture', chapter:'001', chapterFingerprint:'fingerprint'};
const state = {chapters:{'fixture/001':{status:'interrupted',agentId:'bc-retained',chapterFingerprint:'fingerprint'}}};
const chapter = {content:[]};
write('data/fixture/001.json', chapter);
const coverage = Object.fromEntries(['allUnitsVisited','preflightCandidatesAccountedFor','allNamedPeopleAndMentionsCaptured','allDurableFactsCaptured','allChronologyCaptured','allPersonEventsCaptured','allClaimProvenanceCaptured','allFamilyRelationshipsCaptured','editorialPassCompleted'].map(k=>[k,true]));
write('data/people/extractions/fixture/001.json',{coverage,run:{promptVersion:7},input:{chapterFingerprint:buildInputFingerprint(contentUnits(chapter)).chapterFingerprint}});
write('data/people/generated/extraction-state.json',state);
assert.equal(localCursorRecoveryTargets().length, 1, 'current-looking metadata cannot hide interrupted conversation');
state.chapters['fixture/001'] = {status:'interrupted', chunks:{one:{status:'accepted'}}};
write('data/people/generated/extraction-state.json',state);
assert.equal(localCursorRecoveryTargets().length, 1, 'accepted chunk retained on incomplete chapter is recovery');
state.chapters['fixture/001'].status = 'accepted';
write('data/people/generated/extraction-state.json',state);
assert.equal(localCursorRecoveryTargets().length, 0, 'accepted chapter does not turn archived chunks into new work');
const claim = (lane='cursor-sdk', worker='cursor-a', status='resume-required') => ({lane,worker,status,sticky:true,updatedAt:new Date(0).toISOString(),claimedAt:new Date(0).toISOString()});
const acceptedBytes = fs.readFileSync(path.join(root,'data/people/extractions/fixture/001.json'));
const acceptedHash = createHash('sha256').update(acceptedBytes).digest('hex');
const grokReady = (hash=acceptedHash) => ({...claim('grokbot','grok-a','ready'),note:`Imported direct attachment: 1 people, 2 mentions, 3 claims; sha256 ${hash}`});
const options = {worker:'cursor-a',baseRef:'missing-base'};
const run = (ledger,recovery,ready,worker=options.worker) => reconcileLocalCursorReservationsInLedger(ledger,{...options,worker,recovery,ready});
let ledger = {claims:{'fixture/001':claim()}};
let result = run(ledger,[target],[target]);
assert.equal(ledger.claims['fixture/001'].status,'resume-required','recovery wins over ready');
assert.equal(result.recovery.length,1);
ledger = {claims:{'fixture/001':claim()}};
result = run(ledger,[],[target]);
assert.equal(ledger.claims['fixture/001'].status,'resume-required','metadata-only ready cannot promote existing reservation');
ledger = {claims:{'fixture/001':claim()}};
result = run(ledger,[],[]);
assert.equal(ledger.claims['fixture/001'].status,'resume-required','missing local state cannot release remote sticky claim');
ledger = {claims:{'fixture/001':claim('grokbot','grok-a','ready')}};
result = run(ledger,[],[target]);
assert.equal(ledger.claims['fixture/001'].lane,'grokbot');
assert.equal(result.reservedElsewhere.length,1);
ledger = {claims:{'fixture/001':claim('grokbot','grok-a','ready')}};
result = run(ledger,[target],[target]);
assert.equal(result.reservedElsewhere.length,1, 'foreign ready must report a conflicting recovery');
ledger = {claims:{'fixture/001':claim('cursor-sdk','cursor-other','resume-required')}};
result = run(ledger,[target],[target]);
assert.equal(result.reservedElsewhere.length,1,'synchronization reports another stable cursor owner');
assert.equal(ledger.claims['fixture/001'].worker,'cursor-other');
ledger = {claims:{'fixture/001':claim('cursor-sdk','cursor-a','ready')}};
result = run(ledger,[target],[target]);
assert.equal(result.reservedElsewhere.length,1,'retained recovery must not silently downgrade a ready claim');
assert.equal(ledger.claims['fixture/001'].status,'ready');
for (const retained of [claim(), claim('cursor-sdk','cursor-a','ready'), grokReady('0'.repeat(64)), grokReady(), {...grokReady(),status:'submitted'}]) {
  ledger = {claims:{'fixture/001':retained}};
  reconcileLocalCursorReservationsInLedger(ledger,{...options,baseRef:'HEAD',recovery:[],ready:[]});
  assert.deepEqual(ledger.claims['fixture/001'],retained,'current base metadata and arbitrary notes must not release a claim');
  const check = reservePeopleTargetsInLedger(ledger,[target],{lane:'cursor-sdk',worker:'new-worker',limit:1});
  assert.equal(check.blocked.length,1,'claim path must preserve the existing owner');
}
ledger = {claims:{'fixture/001':grokReady()}};
result = reconcileLocalCursorReservationsInLedger(ledger,{...options,baseRef:'HEAD',recovery:[],ready:[target]});
assert.equal(ledger.claims['fixture/001'].lane,'grokbot', 'matching base cannot hide a live collision');
assert.equal(result.reservedElsewhere.length,1);
ledger = {claims:{'fixture/001':grokReady()}};
result = reconcileLocalCursorReservationsInLedger(ledger,{...options,baseRef:'HEAD',recovery:[target],ready:[target]});
assert.equal(result.reservedElsewhere.length,1);
assert.equal(ledger.claims['fixture/001'].lane,'grokbot');
const unrelated = {book:'fixture',chapter:'002',chapterFingerprint:'another-fingerprint'};
ledger = {claims:{'fixture/001':grokReady()}};
result = reconcileLocalCursorReservationsInLedger(ledger,{...options,baseRef:'HEAD',recovery:[target,unrelated],ready:[]});
assert.equal(result.reservedElsewhere.length,1,'conflicting chapter is retained and reported');
assert.equal(result.recovery.length,1,'unrelated work remains synchronizable');
assert.equal(ledger.claims['fixture/001'].lane,'grokbot');
assert.equal(ledger.claims['fixture/002'].worker,'cursor-a');
for (const status of ['resume-required','ready']) {
  const existing = claim('cursor-sdk','cursor-other',status);
  ledger = {claims:{'fixture/001':existing}};
  const reservation = reservePeopleTargetsInLedger(ledger,[target],{lane:'cursor-sdk',worker:'cursor-a',limit:1});
  assert.equal(reservation.claimed.length,0, 'direct reservation cannot adopt foreign sticky claim');
  assert.equal(reservation.blocked.length,1);
  assert.equal(ledger.claims['fixture/001'].worker,'cursor-other');
  assert.equal(cursorClaimAvailableToWorker(existing,'cursor-a'),false);
  assert.equal(cursorClaimAvailableToWorker(existing,'cursor-other'),status === 'resume-required');
  if (status === 'ready') {
    const sameOwner = reservePeopleTargetsInLedger(ledger,[target],{lane:'cursor-sdk',worker:'cursor-other',limit:1});
    assert.equal(sameOwner.claimed.length,0,'ready work must not be redispatched to its owner');
  }
}
assert.equal(cursorClaimAvailableToWorker(null,'cursor-a'),true);
const schedulerSource = fs.readFileSync(path.join(root,'scripts/sdk-people-extract.mjs'),'utf8');
const schedulerFunction = schedulerSource.match(/function availableToCursorLane\(target, ledger, workerId\) \{[\s\S]*?\n\}/u)?.[0];
assert.ok(schedulerFunction, 'scheduler ownership filter must be present');
const available = new Function('workQueueChapterKey','cursorClaimAvailableToWorker',`${schedulerFunction}; return availableToCursorLane`)((t)=>`${t.book}/${t.chapter}`,cursorClaimAvailableToWorker);
assert.equal(available(target,{claims:{'fixture/001':claim('cursor-sdk','cursor-other')}},'cursor-a'),false,'scheduler and broker agree about foreign recovery');
assert.equal(available(target,{claims:{'fixture/001':claim()}},'cursor-a'),true,'scheduler admits stable owner');
ledger = {claims:{}};
result = run(ledger,[],[target]);
assert.equal(ledger.claims['fixture/001'].status,'ready', 'unreserved local ready path remains available');
console.log('queue recovery focused checks passed');
