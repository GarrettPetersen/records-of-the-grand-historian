// Offline control for an exact staging scripts snapshot. Never publishes data.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { buildReviewDossier, verifyReview } from './reconciliation-review-contract-20261020-incomplete.mjs';
const fixture = path.resolve(process.argv[2] ?? '');
if (!fixture.startsWith('/tmp/jinshu129-contract.') || process.env.PEOPLE_REPO_ROOT !== fixture) throw Error('Isolated staging fixture required');
const mod = name => import(pathToFileURL(path.join(fixture, 'scripts', name)).href);
const { buildPeopleExtractionPacket } = await mod('build-people-extraction-packet.mjs');
const { validateCompactPeopleExtraction } = await mod('validate-people-extraction.mjs');
const { reconcileExtractionAfterRepairs } = await mod('lib/people-translation-repairs.mjs');
const source = JSON.parse(fs.readFileSync('data/jinshu/129.json'));
const candidate = JSON.parse(fs.readFileSync('research/people/jinshu129-rebased-editorial-dossier-20261020-incomplete.json')).candidate;
const packet = buildPeopleExtractionPacket('jinshu', '129', { chapterData: source });
const extraction = validateCompactPeopleExtraction(candidate, packet, { strictAliasDispositions: true }).normalized;
const next = structuredClone(source);
const sentence = next.content.flatMap(block => block.sentences ?? []).find(s => s.id === 's0184');
const english = sentence.translations.find(t => t.lang === 'en');
assert.ok(english.idiomatic.includes('visit to Yi and submitted'));
english.idiomatic = english.idiomatic.replace('visit to Yi and submitted', 'visit to Yi in the east and submitted');
const revised = buildPeopleExtractionPacket('jinshu', '129', { chapterData: next });
const result = reconcileExtractionAfterRepairs(extraction, revised, { previousPacket: packet });
const id = 'jinshu:129:cand_8a551c2a741c2b24';
assert.ok(result.extraction.candidateDispositions.some(row => row.candidate === id), 'control requires unsafe surviving disposition');
const context = { rawByteHashes: Object.fromEntries(['source', 'packet', 'extraction', 'editorialHistory'].map(key => [key, 'a'.repeat(64)])), dependencies: Object.fromEntries(['scanner', 'glossary', 'code'].map(key => [key, 'b'.repeat(64)])), authors: ['fixture-author'], downstreamReferences: [], editorialHistory: {}, historicalPacketReceipt: 'fixture-only-not-authenticated' };
const before = { source, extraction, packet, context };
const after = { source: next, extraction: result.extraction, packet: revised, context };
const dossier = buildReviewDossier(before, after);
assert.ok(dossier.changes.some(change => change.path.includes('/source/')));
assert.ok(dossier.changes.some(change => change.path.includes('/extraction/')));
assert.ok(dossier.changes.some(change => change.path.includes('/packet/')));
await assert.rejects(() => verifyReview(before, after, { version: 1, beforeHash: dossier.beforeHash, afterHash: dossier.afterHash, changesHash: dossier.changesHash, reviewer: 'self-declared', decisions: [] }, { verifyProvenance: async () => false, verifyReviewer: async () => false }));
console.log(`Staged unsafe reconciliation recorded ${dossier.changes.length} structural changes; unverified approval rejected. Fixture has fake provenance and is not a chapter review.`);
